import { UILanguage } from '../types';

export type SupportedUILang = 'ru' | 'en' | 'es' | 'de' | 'fr' | 'zh' | 'uk' | 'it';

export function resolveLanguage(settingLang?: UILanguage): SupportedUILang {
  if (settingLang && settingLang !== 'auto') {
    return settingLang;
  }

  if (typeof navigator !== 'undefined') {
    const nav = (navigator.language || (navigator as any).userLanguage || '').toLowerCase();
    if (nav.startsWith('ru') || nav.startsWith('be') || nav.startsWith('uk') || nav.startsWith('kk')) {
      return 'ru';
    }
    if (nav.startsWith('es')) return 'es';
    if (nav.startsWith('de')) return 'de';
    if (nav.startsWith('fr')) return 'fr';
    if (nav.startsWith('zh')) return 'zh';
    if (nav.startsWith('uk')) return 'uk';
    if (nav.startsWith('it')) return 'it';
  }

  return 'en';
}

